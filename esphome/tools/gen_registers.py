#!/usr/bin/env python3
"""Generate the ESPHome C++ register table and entity package.

Reads the shared register description in registers.toml and writes:

    esphome/components/solarlife_mppt/registers.h
    esphome/components/solarlife_mppt/registers.cpp
    esphome/packages/solarlife_mppt.yaml

The C++ table and the package only contain the ranges the bridge reads and
writes, so unused registers do not take flash space.

Run from the repository root after editing registers.toml:

    python esphome/tools/gen_registers.py
"""

import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "registers.toml"
COMPONENT = ROOT / "esphome" / "components" / "solarlife_mppt"
PACKAGE = ROOT / "esphome" / "packages" / "solarlife_mppt.yaml"

# The ranges the bridge reads and writes. The C++ table and the entity package
# only contain these registers, like the Python client.
READ_RANGES = [(0x3030, 0x3058), (0x9021, 0x902C)]
WRITE_RANGE = (0x0000, 0x000C)

# Sub-device the MPPT entities belong to. The example YAML declares it under
# esphome: devices:, so Home Assistant shows the bridge as its own device.
DEVICE_ID = "solarlife"

DEVICE_CLASSES = {
    "V": "voltage",
    "A": "current",
    "W": "power",
    "kWh": "energy",
    "°C": "temperature",
}
STATE_CLASSES = {"kWh": "total_increasing"}

C_KINDS = {
    "number": "NUMBER",
    "flag": "BOOL",
    "enum": "ENUM",
    "digits": "DIGITS",
    "packed_time": "PACKED_TIME",
}


def c_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def c_float(value):
    text = f"{value:.6g}"
    if "." not in text and "e" not in text:
        text += ".0"
    return text + "f"


def decimals_for(divisor):
    if divisor >= 100:
        return 2
    if divisor >= 10:
        return 1
    return 0


def yaml_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load_registers():
    with SOURCE.open("rb") as file:
        return tomllib.load(file)["register"]


def in_package(address):
    return any(start <= address <= end for start, end in READ_RANGES + [WRITE_RANGE])


def is_writable(register):
    return any(code in register["function_codes"] for code in (0x05, 0x06, 0x10))


def export(register):
    kind = register["format"]["kind"]
    if kind not in C_KINDS:
        raise ValueError(f"{register['name']} uses an unknown format '{kind}'")
    labels = list(register["format"].get("labels", []))
    mask = register["format"].get("mask", 1 if kind == "flag" else 0)
    return {
        "address": register["address"],
        "name": register["name"],
        "friendly_name": register["friendly_name"],
        "unit": register["format"].get("unit", ""),
        "divisor": register["format"].get("divisor", 1),
        "is_32_bit": register.get("is_32_bit", False),
        "is_signed": register.get("is_signed", False),
        "function_codes": register["function_codes"],
        "is_writable": is_writable(register),
        "write_fc": 0x05 if 0x05 in register["function_codes"] else 0x06,
        "kind": kind,
        "shift": register["format"].get("shift", 0),
        "mask": mask,
        "labels": labels,
        "digits": register["format"].get("digits", 0),
        "clamp": register["format"].get("clamp", 0),
    }


def write_header():
    text = """// Generated by esphome/tools/gen_registers.py. Do not edit.
#pragma once

#include <cstddef>
#include <cstdint>

namespace esphome::solarlife_mppt {

enum class RegisterKind : uint8_t { NUMBER, BOOL, ENUM, DIGITS, PACKED_TIME };

struct Register {
  uint16_t address;
  const char *name;
  const char *unit;
  float divisor;
  uint16_t shift;
  uint16_t mask;
  uint8_t write_fc;
  bool is_32_bit;
  bool is_signed;
  RegisterKind kind;
  const char *const *labels;
  uint8_t label_count;
  uint8_t digits;
  uint8_t clamp;
};

extern const Register REGISTERS[];
extern const size_t REGISTER_COUNT;

}  // namespace esphome::solarlife_mppt
"""
    (COMPONENT / "registers.h").write_text(text)


def write_source(registers):
    lines = [
        "// Generated by esphome/tools/gen_registers.py. Do not edit.",
        '#include "registers.h"',
        "",
        "namespace esphome::solarlife_mppt {",
        "namespace {",
        "",
    ]
    label_arrays = []
    for index, reg in enumerate(registers):
        if reg["kind"] != "enum":
            continue
        name = f"LABELS_{index}"
        labels = reg["labels"] + [""] * (reg["mask"] + 1 - len(reg["labels"]))
        values = ", ".join(c_string(label) for label in labels)
        label_arrays.append(f"const char *const {name}[] = {{{values}}};")
    lines.extend(label_arrays)
    lines.extend(["", "}  // namespace", "", "const Register REGISTERS[] = {"])

    for index, reg in enumerate(registers):
        labels = f"LABELS_{index}" if reg["kind"] == "enum" else "nullptr"
        label_count = reg["mask"] + 1 if reg["kind"] == "enum" else 0
        lines.append(
            "  {"
            f"0x{reg['address']:04X}, {c_string(reg['name'])}, {c_string(reg['unit'])}, "
            f"{c_float(reg['divisor'])}, {reg['shift']}, {reg['mask']}, 0x{reg['write_fc']:02X}, "
            f"{'true' if reg['is_32_bit'] else 'false'}, {'true' if reg['is_signed'] else 'false'}, "
            f"RegisterKind::{C_KINDS[reg['kind']]}, {labels}, {label_count}, "
            f"{reg['digits']}, {reg['clamp']}"
            "},"
        )
    lines.extend(
        [
            "};",
            "",
            "const size_t REGISTER_COUNT = sizeof(REGISTERS) / sizeof(REGISTERS[0]);",
            "",
            "}  // namespace esphome::solarlife_mppt",
            "",
        ]
    )
    (COMPONENT / "registers.cpp").write_text("\n".join(lines))


def add_common_number_fields(item, reg, accuracy=True):
    unit = reg["unit"]
    if unit:
        item.append(f"    unit_of_measurement: {yaml_string(unit)}")
        if accuracy:
            item.append(f"    accuracy_decimals: {decimals_for(reg['divisor'])}")
    if unit in DEVICE_CLASSES:
        item.append(f"    device_class: {DEVICE_CLASSES[unit]}")
    if unit in STATE_CLASSES:
        item.append(f"    state_class: {STATE_CLASSES[unit]}")


def entity_base(reg, name):
    return (
        "  - platform: solarlife_mppt\n"
        "    solarlife_mppt_id: mppt\n"
        f"    device_id: {DEVICE_ID}\n"
        f"    register: {reg['name']}\n"
        # Register names repeat across controller blocks, so the entity pins the
        # address it belongs to instead of trusting a name-only lookup.
        f"    address: 0x{reg['address']:04X}\n"
        f"    name: {yaml_string(name)}"
    )


def numeric_item(reg, writable):
    item = entity_base(reg, reg["friendly_name"]).splitlines()
    add_common_number_fields(item, reg, accuracy=not writable)
    if writable:
        divisor = reg["divisor"]
        raw_max = 32767 if reg["is_signed"] else 65535
        if reg["is_32_bit"]:
            raw_max = 2147483647 if reg["is_signed"] else 4294967295
        item.append("    mode: box")
        item.append("    min_value: 0")
        item.append(f"    max_value: {raw_max / divisor:.6g}")
        item.append(f"    step: {1 / divisor:.6g}")
    return "\n".join(item)


def write_package(registers):
    sensors, binary_sensors, text_sensors, switches, buttons, numbers, selects = (
        [],
        [],
        [],
        [],
        [],
        [],
        [],
    )

    for reg in registers:
        if not in_package(reg["address"]):
            continue
        name = reg["friendly_name"]
        kind = reg["kind"]

        if kind == "flag":
            binary_sensors.append(entity_base(reg, name))
        elif kind == "enum" and reg["is_writable"]:
            # Multi-value enums use select, two-value enums use switch, and
            # write-only enums use button.
            labels = reg["labels"]
            base = entity_base(reg, name)
            if labels and not labels[0]:
                buttons.append(base + "\n    icon: mdi:play-circle-outline")
            elif len(labels) <= 2:
                switches.append(base + "\n    icon: mdi:toggle-switch")
            else:
                options = "\n".join(f"      - {yaml_string(label)}" for label in labels)
                selects.append(
                    base
                    + "\n    icon: mdi:format-list-bulleted\n    options:\n"
                    + options
                )
        elif kind in ("enum", "digits"):
            text_sensors.append(entity_base(reg, name))
        elif kind in ("number", "packed_time") and reg["is_writable"]:
            numbers.append(numeric_item(reg, True))
        elif kind in ("number", "packed_time"):
            sensors.append(numeric_item(reg, False))
        else:
            raise ValueError(f"cannot create an entity for {reg['name']} ({kind})")

    sections = []
    for key, items in [
        ("sensor", sensors),
        ("number", numbers),
        ("binary_sensor", binary_sensors),
        ("text_sensor", text_sensors),
        ("select", selects),
        ("switch", switches),
        ("button", buttons),
    ]:
        if items:
            sections.append(f"# {key}\n{key}:\n" + "\n".join(items))
    PACKAGE.write_text(
        "# Generated by esphome/tools/gen_registers.py. Do not edit.\n"
        "# Entities for the registers the hub reads and writes. See esphome/README.md.\n\n"
        + "\n\n".join(sections)
        + "\n"
    )


def main():
    registers = [export(reg) for reg in load_registers()]
    registers.sort(key=lambda reg: (reg["address"], reg["name"]))
    used = [reg for reg in registers if in_package(reg["address"])]

    write_header()
    write_source(used)
    write_package(registers)

    counts = {}
    for reg in used:
        counts[reg["kind"]] = counts.get(reg["kind"], 0) + 1
    print(f"{len(used)} registers in the C++ table ({counts} exposed as entities)")


if __name__ == "__main__":
    main()
